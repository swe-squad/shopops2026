"""Regenerate checked-in read DTOs from this service's isolated migrated schema."""

from pathlib import Path

from app.api.reads import MARTS
from app.storage.db import connect
from app.storage.migrations import migrate

TYPES = {
    "text": "str",
    "boolean": "bool",
    "integer": "int",
    "bigint": "int",
    "numeric": "Decimal",
    "timestamp with time zone": "datetime",
    "date": "date",
    "jsonb": "dict | list",
}


def main() -> None:
    migrate()
    relations = [("mart", name) for name in MARTS] + [
        ("raw", "documents"),
        ("access", "user_shop_access"),
    ]
    lines = [
        '"""Generated by scripts.export_contracts; concrete read-only API contracts."""',
        "from datetime import date, datetime",
        "from decimal import Decimal",
        "from pydantic import BaseModel",
        "",
    ]
    registry = {}
    with connect() as conn:
        for schema, table in relations:
            name = "".join(part.title() for part in table.split("_"))
            registry[table] = name
            lines.append(f"class {name}(BaseModel):")
            columns = conn.execute(
                "SELECT column_name,data_type FROM information_schema.columns "
                "WHERE table_schema=%s AND table_name=%s ORDER BY ordinal_position",
                (schema, table),
            ).fetchall()
            for column in columns:
                lines.append(f"    {column['column_name']}: {TYPES[column['data_type']]} | None")
            lines.append("")
    lines.append("READ_MODELS = {")
    lines.extend(f'    "{table}": {name},' for table, name in registry.items())
    lines.append("}\n")
    Path("app/api/derived_models.py").write_text("\n".join(lines), encoding="utf-8")


if __name__ == "__main__":
    main()
