import { test, expect } from '@playwright/test'
import { browserApp, chatApp, expectFixedParent, showClient, testToken, unlock } from './helpers'

test('browser tabs preserve drafts, history and keyboard selection', async ({ page }) => {
  await page.goto('/')
  const browser = browserApp(page)
  await unlock(browser, 'Unlock workspace')
  await browser.getByLabel('Browser address').fill('/shop/incidents')
  await browser.getByRole('button', { name: 'Open address', exact: true }).click()
  await browser.getByRole('tabpanel').getByLabel('Title', { exact: true }).fill('Unsaved tab draft')
  await browser.getByRole('button', { name: 'New browser tab' }).click()
  await expect(browser.getByRole('tab', { selected: true })).toHaveAccessibleName('Overview — tab 2')
  await browser.getByLabel('Browser address').fill('/shop/incidents')
  await browser.getByRole('button', { name: 'Open address', exact: true }).click()
  await browser.getByRole('button', { name: 'Go back', exact: true }).click()
  await expect(browser.getByLabel('Browser address')).toHaveValue(/\/shop\/overview$/)
  await browser.getByRole('tab', { name: 'Incidents — tab 1', exact: true }).click()
  await expect(browser.getByRole('tabpanel').getByLabel('Title', { exact: true })).toHaveValue('Unsaved tab draft')
  await browser.getByRole('tab', { name: 'Incidents — tab 1', exact: true }).press('ArrowRight')
  await expect(browser.getByRole('tab', { selected: true })).toHaveAccessibleName('Overview — tab 2')
  await browser.getByRole('tab', { selected: true }).press('Delete')
  await expect(browser.getByRole('tab')).toHaveCount(1)
  await expect(browser.getByRole('tabpanel').getByLabel('Title', { exact: true })).toHaveValue('Unsaved tab draft')
  await expectFixedParent(page)
})

test('real streamed reply opens the active browser tab and preserves independent sessions', async ({ page }, testInfo) => {
  await page.goto('/')
  const browser = browserApp(page)
  const chat = chatApp(page)
  await unlock(browser, 'Unlock workspace')
  await unlock(chat, 'Unlock chat')
  await browser.getByRole('button', { name: 'New browser tab' }).click()
  await chat.getByLabel('Message', { exact: true }).fill('Show the UI test fixture')
  await chat.getByRole('button', { name: 'Send message' }).click()
  await expect(chat.getByRole('table').last()).toBeVisible()
  await expect(chat.getByRole('button', { name: 'Stop response' })).not.toBeAttached()
  const navigation = page.waitForResponse(response => response.url().endsWith('/api/operations/navigation') && response.request().method() === 'POST')
  await chat.getByRole('link', { name: 'Open incidents', exact: true }).last().click()
  expect((await navigation).status()).toBe(201)
  await expect(browser.getByLabel('Browser address')).toHaveValue(/\/shop\/incidents$/)
  await expect(browser.getByRole('tab', { selected: true })).toHaveAccessibleName('Incidents — tab 2')
  await expect(browser.getByRole('tab', { name: 'Connections — tab 1', exact: true })).toBeVisible()
  expect(page.url()).toBe('http://localhost:5175/')
  await page.screenshot({ path: testInfo.outputPath('workspace-desktop.png') })

  await chat.getByLabel('Message', { exact: true }).fill('Draft kept across views')
  const chatFrame = page.frames().find(frame => frame.url().startsWith('http://localhost:5174'))!
  await page.setViewportSize({ width: 375, height: 812 })
  await showClient(page, 'Chat')
  await expect(chat.getByLabel('Message', { exact: true })).toHaveValue('Draft kept across views')
  await showClient(page, 'Browser')
  await page.getByRole('button', { name: 'Reload browser app' }).click()
  await expect(browser.getByLabel('Workspace access token')).toBeVisible()
  await showClient(page, 'Chat')
  expect(page.frames()).toContain(chatFrame)
  await expect(chat.getByLabel('Message', { exact: true })).toHaveValue('Draft kept across views')
  await expectFixedParent(page)
})

test('only child content scrolls and incoming text respects a reader scrolling up', async ({ page, request }) => {
  for (let index = 0; index < 28; index++) {
    const response = await request.post('http://127.0.0.1:8000/api/operations/incidents', {
      headers: { Authorization: `Bearer ${testToken}` },
      data: { title: `Browser scroll fixture ${index}`, detail: 'Temporary test database only.' },
    })
    expect(response.status()).toBe(201)
  }
  await page.goto('/')
  const browser = browserApp(page)
  const chat = chatApp(page)
  await unlock(browser, 'Unlock workspace')
  await unlock(chat, 'Unlock chat')
  await browser.getByLabel('Browser address').fill('/shop/incidents')
  await browser.getByRole('button', { name: 'Open address', exact: true }).click()
  const shop = browser.locator('.shop-page:visible')
  await expect(browser.getByText('Browser scroll fixture 27', { exact: true })).toBeAttached()
  await shop.hover()
  await page.mouse.wheel(0, 650)
  await expect.poll(() => shop.evaluate(element => element.scrollTop)).toBeGreaterThan(0)
  await expect(browser.getByLabel('Browser address')).toBeInViewport()
  await expectFixedParent(page)

  await chat.getByLabel('Message', { exact: true }).fill('Long scroll test fixture')
  await chat.getByRole('button', { name: 'Send message' }).click()
  const log = chat.getByRole('log', { name: 'Conversation' })
  await expect(chat.getByText('Test note 8.', { exact: false })).toBeAttached()
  await log.hover()
  await page.mouse.wheel(0, -20000)
  await expect.poll(() => log.evaluate(element => element.scrollTop)).toBe(0)
  await expect(chat.getByText('Test note 25.', { exact: false })).toBeAttached()
  expect(await log.evaluate(element => element.scrollTop)).toBeLessThan(20)
  await expect(chat.getByRole('button', { name: /Jump to latest/ })).toBeVisible()
  await expect(chat.getByRole('button', { name: 'Stop response' })).not.toBeAttached()
  await chat.getByRole('button', { name: /Jump to latest/ }).click()
  await expect.poll(() => log.evaluate(element => element.scrollHeight - element.scrollTop - element.clientHeight)).toBeLessThan(2)
  await expect(chat.getByLabel('Message', { exact: true })).toBeInViewport()
  await expectFixedParent(page)
})

test('stopping a response offers explicit history recovery without resending', async ({ page }, testInfo) => {
  let submissions = 0
  page.on('request', request => { if (request.method() === 'POST' && request.url().endsWith('/api/chat/messages')) submissions++ })
  await page.goto('/')
  const chat = chatApp(page)
  await unlock(chat, 'Unlock chat')
  await chat.getByLabel('Message', { exact: true }).fill('Slow fixture for stop testing')
  await chat.getByRole('button', { name: 'Send message' }).click()
  await expect(chat.getByRole('button', { name: 'Stop response' })).toBeVisible()
  await expect(chat.getByRole('article', { name: 'Agent message' }).last().getByText('Browser test fixture — no live shop data.', { exact: true })).toBeVisible()
  await chat.getByRole('button', { name: 'Stop response' }).click()
  const recovery = chat.getByRole('group', { name: 'Conversation recovery' })
  await expect(recovery.getByRole('button', { name: 'Load conversation' })).toBeVisible()
  await page.screenshot({ path: testInfo.outputPath('chat-recovery.png') })
  await recovery.getByRole('button', { name: 'Load conversation' }).click()
  await expect(chat.getByLabel('Message', { exact: true })).toBeEnabled()
  expect(submissions).toBe(1)
})

test('Telegram-style composer and chat menu support keyboard interaction', async ({ page }, testInfo) => {
  let submissions = 0
  page.on('request', request => { if (request.method() === 'POST' && request.url().endsWith('/api/chat/messages')) submissions++ })
  await page.goto('/')
  const chat = chatApp(page)
  await unlock(chat, 'Unlock chat')
  const composer = chat.getByLabel('Message', { exact: true })
  await composer.fill('First line')
  await composer.press('Shift+Enter')
  await composer.pressSequentially('Second line')
  await expect(composer).toHaveValue('First line\nSecond line')
  expect(submissions).toBe(0)
  await composer.press('Enter')
  await expect(chat.getByRole('article', { name: 'Your message' }).last()).toContainText('Second line')
  await expect(chat.getByRole('article', { name: 'Agent message' }).last().getByText('Browser test fixture — no live shop data.', { exact: true })).toBeVisible()
  await expect(chat.getByRole('button', { name: 'Stop response' })).not.toBeAttached()
  await expect(composer).toHaveValue('')
  await expect(composer).toBeFocused()
  expect(submissions).toBe(1)

  await composer.fill('Draft survives a history refresh')
  const menu = chat.getByRole('button', { name: 'Chat menu', exact: true })
  await menu.focus()
  await menu.press('Enter')
  await expect(chat.getByRole('menu')).toBeVisible()
  await expect(chat.getByRole('menuitem').first()).toBeFocused()
  await chat.getByRole('menuitem').first().hover()
  await page.screenshot({ path: testInfo.outputPath('chat-menu.png') })
  await chat.getByRole('menuitem').first().press('ArrowDown')
  await expect(chat.getByRole('menuitem').last()).toBeFocused()
  await chat.getByRole('menuitem').last().press('Escape')
  await expect(chat.getByRole('menu')).not.toBeAttached()
  await expect(menu).toBeFocused()
  await menu.click()
  await composer.click()
  await expect(chat.getByRole('menu')).not.toBeAttached()
  await menu.click()
  await chat.getByRole('menuitem', { name: 'Load conversation', exact: true }).click()
  await expect(composer).toBeEnabled()
  await expect(composer).toHaveValue('Draft survives a history refresh')
  await menu.click()
  await chat.getByRole('menuitem', { name: 'Lock', exact: true }).click()
  await expect(chat.getByLabel('Workspace access token')).toBeVisible()
  await expectFixedParent(page)
})

test('wide Markdown scrolls inside the phone without widening the parent', async ({ page }) => {
  await page.setViewportSize({ width: 375, height: 812 })
  await page.goto('/')
  await showClient(page, 'Chat')
  const chat = chatApp(page)
  await unlock(chat, 'Unlock chat')
  await chat.getByLabel('Message', { exact: true }).fill('Wide fixture for table and code testing')
  await chat.getByRole('button', { name: 'Send message' }).click()
  await expect(chat.getByRole('button', { name: 'Stop response' })).not.toBeAttached()
  const bubble = chat.getByRole('article', { name: 'Agent message' }).last()
  for (const content of [bubble.getByRole('region', { name: 'Message table' }).last(), bubble.getByRole('region', { name: 'Message code' }).last()]) {
    await expect(content).toBeAttached()
    const dimensions = await content.evaluate(element => ({ width: element.clientWidth, scroll: element.scrollWidth }))
    expect(dimensions.scroll).toBeGreaterThan(dimensions.width)
    await content.focus()
    await content.press('End')
    await content.press('ArrowRight')
    await expect.poll(() => content.evaluate(element => element.scrollLeft)).toBeGreaterThan(0)
  }
  await expect(chat.getByLabel('Message', { exact: true })).toBeInViewport()
  await expectFixedParent(page)
})
